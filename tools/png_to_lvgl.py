#!/usr/bin/env python3
"""Convert a PNG into an LVGL 9 image (LV_COLOR_FORMAT_RGB565A8) C file.

    pip install pillow
    python tools/png_to_lvgl.py <in.png> <size_px> <c_name> <out.c> [--outline]

The image is fitted into a size_px square (aspect kept).  --outline adds the
white outline the BK brand guide asks for on dark backgrounds (guide p.05):
the silhouette is grown at high resolution, filled white, and the logo is
composited on top before downscaling, so the edge stays smooth.
"""
import argparse

from PIL import Image, ImageFilter


def build(src, size, outline):
    im = Image.open(src).convert("RGBA")
    work = size * 4  # supersample, then downscale once
    im.thumbnail((work, work), Image.LANCZOS)
    if outline:
        pad = max(4, work // 28)
        canvas = Image.new("RGBA", (im.width + 2 * pad, im.height + 2 * pad), (0, 0, 0, 0))
        canvas.paste(im, (pad, pad), im)
        alpha = canvas.getchannel("A").point(lambda a: 255 if a > 40 else 0)
        grown = alpha.filter(ImageFilter.MaxFilter(2 * pad - 1 if pad % 2 == 0 else 2 * pad + 1))
        white = Image.new("RGBA", canvas.size, (255, 255, 255, 255))
        white.putalpha(grown)
        white.alpha_composite(canvas)
        im = white
    im.thumbnail((size, size), Image.LANCZOS)
    return im


def to_c(im, name):
    w, h = im.size
    px = list(im.getdata())
    rgb = bytearray()
    alpha = bytearray()
    for r, g, b, a in px:
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        rgb += bytes((v & 0xFF, v >> 8))  # little-endian, as LVGL expects
        alpha.append(a)
    data = rgb + alpha
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{x:02x}" for x in data[i:i + 24]) + ",")
    body = "\n".join(lines)
    return f"""// Generated by tools/png_to_lvgl.py - do not edit.
#ifdef LV_LVGL_H_INCLUDE_SIMPLE
#include "lvgl.h"
#else
#include "lvgl/lvgl.h"
#endif

static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_map[] = {{
{body}
}};

const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565A8,
        .flags = 0,
        .w = {w},
        .h = {h},
        .stride = {w * 2},
    }},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
"""


def main():
    p = argparse.ArgumentParser()
    p.add_argument("src")
    p.add_argument("size", type=int)
    p.add_argument("name")
    p.add_argument("out")
    p.add_argument("--outline", action="store_true")
    p.add_argument("--preview", help="also save a PNG preview on black")
    a = p.parse_args()
    im = build(a.src, a.size, a.outline)
    with open(a.out, "w", newline="\n") as f:
        f.write(to_c(im, a.name))
    if a.preview:
        bg = Image.new("RGBA", (im.width + 20, im.height + 20), (0, 0, 0, 255))
        bg.alpha_composite(im, (10, 10))
        bg.convert("RGB").save(a.preview)
    print(f"{a.out}: {a.name} {im.width}x{im.height}")


if __name__ == "__main__":
    main()
